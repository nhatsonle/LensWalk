from pydantic import BaseModel, Field
from typing import List, Dict, Any, Union, Optional, Literal

class TimeInterval(BaseModel):
    start_sec: float = Field(..., description="Start time in seconds.")
    end_sec: float = Field(..., description="End time in seconds.")

class Observation(BaseModel):
    interval: Union[TimeInterval, List[TimeInterval]] = Field(..., description="Time interval(s) covered by this observation.")
    description: str = Field(..., description="Text description of observed events, objects, or scenes.")
    confidence: float = Field(default=1.0, description="Confidence score for the observation.")
    subject_registry: Dict[str, Any] = Field(default_factory=dict, description="Structured subject registry for observed entities.")
    metadata: Dict[str, Any] = Field(default_factory=dict)

class Budget(BaseModel):
    sampled_frames_count: int = Field(..., description="Total sampled frame count.")
    frame_indices: List[int] = Field(..., description="Sampled frame indices.")

class Provenance(BaseModel):
    tool_name: str = Field(..., description="Tool name.")
    tool_params: Dict[str, Any] = Field(..., description="Raw tool parameters.")

class ToolOutput(BaseModel):
    observations: List[Observation] = Field(..., description="Structured observations produced by this tool call.")
    coverage: List[TimeInterval] = Field(..., description="All time intervals covered by this tool call.")
    used_budget: Budget = Field(..., description="Sampling budget consumed by this tool call.")
    provenance: Provenance = Field(..., description="Tool-call provenance.")

class SubjectRegistryState(BaseModel):
    subject_registry: Dict[str, Any] = Field(default_factory=dict, description="Aggregated subject registry.")


class Hypothesis(BaseModel):
    """Single temporal search hypothesis assigned by the Orchestrator to an Actor."""

    hypothesis_id: str = Field(..., description="Identifier such as H1, H2, H3.")
    interval: TimeInterval = Field(..., description="Candidate time interval in seconds.")
    sub_query: str = Field(..., description="Focused verification question for this interval.")
    rationale: str = Field(default="", description="Reason why this interval may contain evidence.")
    allocated_frames: int = Field(default=32, ge=1, description="Frame budget allocated to this Actor.")


class OrchestratorPlan(BaseModel):
    """Phase-1 multi-hypothesis plan generated by the Orchestrator."""

    reasoning: str = Field(..., description="Justification for hypothesis count, boundaries, and budget split.")
    hypotheses: List[Hypothesis] = Field(..., min_length=1, max_length=3, description="1 to 3 search hypotheses.")


class ActorEvidenceItem(BaseModel):
    """Concrete timestamped visual evidence extracted by an Actor."""

    interval: TimeInterval = Field(..., description="Observed video interval.")
    visual_fact: str = Field(..., description="Directly observed visual facts without unsupported guessing.")
    relevance: Literal["direct", "partial", "none"] = Field(default="partial")


class ActorReport(BaseModel):
    """Structured report submitted by an Actor after exploring one hypothesis."""

    hypothesis_id: str = Field(..., description="Identifier of the explored hypothesis.")
    status: Literal["FOUND", "PARTIAL", "NOT_FOUND"] = Field(..., description="Whether sufficient evidence was found.")
    candidate_answer: Optional[str] = Field(default=None, description="Candidate answer if status != NOT_FOUND.")
    confidence: Literal["high", "medium", "low"] = Field(default="low")
    evidences: List[ActorEvidenceItem] = Field(default_factory=list)
    uncertainties: str = Field(default="", description="Sampling gaps, ambiguity, or low-FPS caveats.")
    covered_intervals: List[TimeInterval] = Field(default_factory=list)
    used_frames: int = Field(default=0, ge=0)


class VerifySegmentSpec(BaseModel):
    """Segment specification for final cross-hypothesis stitched verification."""

    interval: TimeInterval
    fps: float = Field(default=1.0, gt=0)


class CoordinatorDecision(BaseModel):
    """Phase-2 Orchestrator decision after reviewing all Actor reports."""

    action: Literal["FINISH", "STITCHED_VERIFY", "FALLBACK_REPLAN"]
    reasoning: str = Field(..., description="Justification for the selected action.")
    final_answer: Optional[str] = Field(default=None)
    verify_segments: Optional[List[VerifySegmentSpec]] = Field(default=None)
    verify_query: Optional[str] = Field(default=None)
    fallback_intervals: Optional[List[TimeInterval]] = Field(default=None)
    fallback_query: Optional[str] = Field(default=None)
