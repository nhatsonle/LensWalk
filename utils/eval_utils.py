from openai import OpenAI
import json
from typing import Any, Dict, Tuple

OPEN_ENDED_INSTRUCTION = """Evaluate whether the model's final answer is correct by comparing it to the ground-truth answer provided for the given question.

You should first extract the final answer from the model's response, and then compare the extracted answer with the ground-truth answer to determine its accuracy.

The final answer generated by the model does not need to match the ground-truth answer word-for-word. However, it should only be considered correct if it demonstrates the exact same technique or concept explicitly and unambiguously equivalent to the ground-truth answer.

Output your response in the following structured format:
{
    "extracted_answer": // str value, the short final answer extracted from the model's response, do not hallucinate one that is not present in the response
    "correct": // boolean value, True if the answer is correct, False otherwise
}
"""

def prepare_evaluation_message_open_ended(example: Dict[str, Any]) -> list[Dict[str, str]]:
    """Build Chat Completions messages for open-ended evaluation."""
    question_context = f"Question: {example['question']}"
    gt_answer = f"Ground Truth Answer: {example['answer']}"
    model_response = f"Model Response to the Question: {example['response']}"
    user_prompt = f"{question_context}\n\n{gt_answer}\n\n{model_response}"
    return [
        {"role": "system", "content": OPEN_ENDED_INSTRUCTION},
        {"role": "user", "content": user_prompt},
    ]

def _open_ended_response_format() -> Dict[str, Any]:
    """Structured Output schema"""
    return {
        "type": "json_schema",
        "json_schema": {
            "name": "evaluation_output",
            "schema": {
                "type": "object",
                "properties": {
                    "extracted_answer": {
                        "type": "string",
                        "description": "Short final answer extracted verbatim from model's response.",
                        "minLength": 1,
                        "maxLength": 200,
                    },
                    "correct": {"type": "boolean"},
                },
                "required": ["extracted_answer", "correct"],
                "additionalProperties": False,
            },
            "strict": True,
        },
    }

def eval_open_ended(
    example: Dict[str, Any],
    client: OpenAI,
    *,
    model: str = "gpt-4o",
    max_tokens: int = 128,
) -> Tuple[bool, str, Dict[str, Any]]:
    """Evaluate an open-ended response with an OpenAI-compatible judge."""
    messages = prepare_evaluation_message_open_ended(example)
    resp_format = _open_ended_response_format()

    resp = client.chat.completions.create(
        model=model,
        messages=messages,
        response_format=resp_format,
        max_tokens=max_tokens,
        temperature=0,
    )

    content = resp.choices[0].message.content or ""
    data = {}
    try:
        data = json.loads(content)
    except Exception:
        try:
            start = content.find("{")
            end = content.rfind("}")
            if start != -1 and end != -1 and end > start:
                data = json.loads(content[start:end+1])
        except Exception:
            data = {}

    extracted = str(data.get("extracted_answer", "")).strip()
    is_correct = bool(data.get("correct", False))

    result = {
        "id": example.get("id"),
        "question": example.get("question"),
        "response": example.get("response"),
        "ground_truth_answer": example.get("answer"),
        "extracted_answer": extracted,
        "correct": is_correct,
    }
    return is_correct, extracted, result
